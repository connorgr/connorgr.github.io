"""Footer ridgeline: a shorter sibling of the header's W6 waves that rises out of
the dark footer. Back ridges sit close to the white page; ridges darken through
grey toward the front, whose fill is the footer's --ink.

Writes/replaces:
  - <svg class="wave-foot"> directly before <footer class="footer"> in index.html
  - the block between /* footer waves */ and /* /footer waves */ in style.css

Usage: python3 tools/footer_ridges.py [site_dir]   (default: the repo root)
"""
import random, re, sys

import os
SITE = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 3200, 80
N = 6
TOP, BOTTOM = 30, 72
X0, X1 = -120, W + 120
rng = random.Random(2017)   # different seed from the header, so the bands don't repeat

def ridge(i):
    yb = TOP + (BOTTOM - TOP) * i / (N - 1)
    t = i / (N - 1)
    x = X0 + rng.uniform(-60, 0)
    d = [f"M{X0},{yb:.1f}L{x:.1f},{yb:.1f}"]
    while x < X1:
        wl = rng.uniform(130, 250)
        h = rng.uniform(8, 24) * (1.1 - 0.3 * t)
        if rng.random() < 0.25:
            h *= 0.45
        rise = wl * rng.uniform(0.6, 0.72); fall = wl - rise
        xc, yc, xe = x + rise, yb - h, x + wl
        d.append(f"C{x + rise * 0.5:.1f},{yb:.1f} {xc - rise * 0.16:.1f},{yc + h * 0.42:.1f} {xc:.1f},{yc:.1f}")
        d.append(f"C{xc + fall * 0.12:.1f},{yc + h * 0.5:.1f} {xe - fall * 0.45:.1f},{yb:.1f} {xe:.1f},{yb:.1f}")
        x = xe
    line = "".join(d)
    return line, line + f"L{x:.1f},{H + 10}L{X0},{H + 10}Z"

paths = []
for i in range(N):
    line, fill = ridge(i)
    paths.append(f'  <path class="fr r{i}" d="{fill}"/>')
    paths.append(f'  <path class="fr-line r{i}" d="{line}"/>')
svg = ('<svg class="wave-foot" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" '
       f'viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" width="100%" height="72">\n'
       + "\n".join(paths) + "\n</svg>\n")

rules = []
for i in range(N):
    t = i / (N - 1)
    # fills: white page -> footer ink, through grey
    rules.append(f".wave-foot .fr.r{i} {{ fill: color-mix(in srgb, var(--ink) {round(100 * t ** 1.6)}%, var(--paper)); }}")
    # lines: faint grey at the back, brand blue in the middle, light grey on the dark front ridges
    if t < 0.35:
        stroke = f"color-mix(in srgb, var(--mid) {round(25 + 90 * t)}%, var(--paper))"
    elif t < 0.8:
        stroke = "var(--blue)"
    else:
        stroke = "#8a8a8a"
    w = round(0.5 + 1.2 * t ** 1.2, 2)
    rules.append(f".wave-foot .fr-line.r{i} {{ stroke: {stroke}; stroke-width: {w}; }}")

css = ("/* footer waves — generated by footer_ridges.py; mirrors the header ridgeline,\n"
       "   fading from the white page into the footer's ink through grey. */\n"
       ".wave-foot { display: block; width: 100%; height: 72px; margin-bottom: -1px; overflow: hidden; }\n"
       ".wave-foot .fr-line { fill: none; stroke-linejoin: miter; stroke-miterlimit: 8; vector-effect: non-scaling-stroke; }\n"
       + "\n".join(rules) + "\n"
       "@media (max-width: 600px) { .wave-foot { height: 56px; } }\n"
       "/* /footer waves */\n")

hp, cp = f"{SITE}/index.html", f"{SITE}/style.css"
h = open(hp, encoding="utf-8").read()
h = re.sub(r'<svg class="wave-foot".*?</svg>\n', "", h, flags=re.S)       # idempotent
assert h.count('<footer class="footer">') == 1
h = h.replace('<footer class="footer">', svg + '<footer class="footer">')
open(hp, "w", encoding="utf-8").write(h)

c = open(cp, encoding="utf-8").read()
c = re.sub(r"/\* footer waves .*?/\* /footer waves \*/\n\n?", "", c, flags=re.S)  # idempotent
anchor = "/* ---------- footer ---------- */\n.footer { background: var(--ink)"
assert c.count(anchor) == 1
c = c.replace(anchor, css + "\n" + anchor)
open(cp, "w", encoding="utf-8").write(c)
print("ok")
