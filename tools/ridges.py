"""Header waves: stacked, occluding ridges with pointed (cusped) crests that fade
toward the sky. Rewrites ONLY the <svg class="wave"> in index.html and the block
between the /* W6: ridgeline swells */ and /* /W6 wave */ markers in style.css,
so other edits to those files are preserved. Output is deterministic (fixed seed).

Usage: python3 tools/ridges.py [site_dir]   (default: the repo root)
"""
import random, re, sys

import os
SITE = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Wide canvas: with preserveAspectRatio="xMidYMax slice" and a fixed CSS height,
# the browser only crops the SIDES until the viewport is wider than
# W * (css height / H). W=3200, H=120, height 110px  ->  no top-cropping below ~2930px.
W, H = 3200, 120
N = 9                       # ridges, back -> front
TOP, BOTTOM = 34, 106       # baseline of back / front ridge (leave headroom for crests)
X0, X1 = -120, W + 120      # overdraw so the ends never show

rng = random.Random(1966)

def ridge(i):
    """Flat troughs, long gentle rise, sharp corner at the crest,
    steeper lee face (wind-driven lean to the right)."""
    yb = TOP + (BOTTOM - TOP) * i / (N - 1)
    t = i / (N - 1)
    x = X0 + rng.uniform(-60, 0)
    d = [f"M{X0},{yb:.1f}L{x:.1f},{yb:.1f}"]
    while x < X1:
        wl = rng.uniform(130, 260)                     # wavelength
        h = rng.uniform(9, 30) * (1.15 - 0.3 * t)      # crest height
        if rng.random() < 0.25:
            h *= 0.45                                  # occasional small swell
        rise = wl * rng.uniform(0.6, 0.72)             # crest sits past centre
        fall = wl - rise
        xc, yc, xe = x + rise, yb - h, x + wl
        c1 = (x + rise * 0.5, yb)                      # leave trough flat
        c2 = (xc - rise * 0.16, yc + h * 0.42)         # arrive steep (up-right)
        c3 = (xc + fall * 0.12, yc + h * 0.5)          # leave steep (down-right) -> corner
        c4 = (xe - fall * 0.45, yb)
        d.append(f"C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {xc:.1f},{yc:.1f}")
        d.append(f"C{c3[0]:.1f},{c3[1]:.1f} {c4[0]:.1f},{c4[1]:.1f} {xe:.1f},{yb:.1f}")
        x = xe
    line = "".join(d)
    return line, line + f"L{x:.1f},{H + 10}L{X0},{H + 10}Z"

paths = []
for i in range(N):
    line, fill = ridge(i)
    paths.append(f'  <path class="ridge r{i}" d="{fill}"/>')
    paths.append(f'  <path class="ridge-line r{i}" d="{line}"/>')

svg = (
    '<svg class="wave" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg" '
    f'viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMax slice" width="100%" height="110">\n'
    f'  <rect class="sea-sky" x="0" y="0" width="{W}" height="{H}"/>\n'
    + "\n".join(paths) + "\n</svg>"
)

# Atmospheric fade: back ridges sit close to the sky (low contrast, thin),
# front ridges reach full blue -> ink at full weight.
rules = []
for i in range(N):
    t = i / (N - 1)
    fill = f"color-mix(in srgb, var(--paper) {round(100 * t)}%, var(--sky))"
    if t <= 0.6:
        stroke = f"color-mix(in srgb, var(--blue) {round(22 + 130 * t)}%, var(--sky))"
    else:
        stroke = f"color-mix(in srgb, var(--ink) {round(250 * (t - 0.6))}%, var(--blue))"
    width = round(0.5 + 1.5 * t ** 1.4, 2)
    rules.append(f".wave .ridge.r{i} {{ fill: {fill}; }}")
    rules.append(f".wave .ridge-line.r{i} {{ stroke: {stroke}; stroke-width: {width}; }}")

START = "/* W6: ridgeline swells"
END = "/* /W6 wave */"
css_block = (
    "/* W6: ridgeline swells — stacked ridges that hide the ones behind them\n"
    "   (Unknown-Pleasures-style ridgeline), with cusped crests. Back ridges fade\n"
    "   toward the sky: lower contrast and thinner lines. Generated by ridges.py. */\n"
    ".wave { display: block; width: 100%; height: 110px; margin-top: -1px; overflow: hidden; }\n"
    ".wave .sea-sky { fill: var(--sky); }\n"
    ".wave .ridge-line { fill: none; stroke-linejoin: miter; stroke-miterlimit: 8;\n"
    "  vector-effect: non-scaling-stroke; }\n"
    + "\n".join(rules) + "\n"
    "@media (max-width: 600px) { .wave { height: 84px; } }\n"
    + END + "\n"
)

html_path, css_path = f"{SITE}/index.html", f"{SITE}/style.css"
html = open(html_path).read()
html, n = re.subn(r'<svg class="wave".*?</svg>', lambda m: svg, html, count=1, flags=re.S)
assert n == 1, "wave svg not found"
open(html_path, "w").write(html)

css = open(css_path).read()
s = css.index(START)
e = css.index(END) + len(END) + 1
css = css[:s] + css_block + css[e:]
open(css_path, "w").write(css)
print("ok", N, "ridges")
